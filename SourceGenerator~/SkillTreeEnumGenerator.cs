using System;
using System.Collections.Generic;
using System.Globalization;
using System.Linq;
using System.Text;
using Game.SkillTree.CodeGeneration;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace FatLarva.SkillTree.Generator
{
    [Generator]
    public sealed class SkillTreeEnumGenerator : ISourceGenerator
    {
        private static readonly DiagnosticDescriptor InvalidManifest = new DiagnosticDescriptor(
            "STENUM001", "Invalid skill tree enum", "{0}", "SkillTree", DiagnosticSeverity.Error, true);
        private static readonly DiagnosticDescriptor DuplicateType = new DiagnosticDescriptor(
            "STENUM002", "Duplicate skill tree enum", "Enum '{0}' is already generated by '{1}'. Give each tree a distinct namespace or type name.",
            "SkillTree", DiagnosticSeverity.Error, true);
        private static readonly DiagnosticDescriptor ExistingType = new DiagnosticDescriptor(
            "STENUM003", "Skill tree enum type exists", "Type '{0}' already exists in the target compilation",
            "SkillTree", DiagnosticSeverity.Error, true);

        public void Initialize(GeneratorInitializationContext context) { }

        public void Execute(GeneratorExecutionContext context)
        {
            var types = new Dictionary<string, string>(StringComparer.Ordinal);
            var trees = new HashSet<string>(StringComparer.Ordinal);
            foreach (var file in context.AdditionalFiles.OrderBy(file => file.Path, StringComparer.Ordinal))
            {
                context.CancellationToken.ThrowIfCancellationRequested();
                if (!file.Path.EndsWith(SkillTreeEnumManifestFormat.FileSuffix, StringComparison.Ordinal)) continue;
                var text = file.GetText(context.CancellationToken);
                SkillTreeEnumManifest manifest = null;
                string error = null;
                if (text == null || !SkillTreeEnumManifestFormat.TryParse(text.ToString(), out manifest, out error))
                {
                    Report(context, file.Path, InvalidManifest, text == null ? "Cannot read enum manifest." : error);
                    continue;
                }
                // A global analyzer can run for many asmdefs; generate a type only in its explicitly named owner.
                if (!string.Equals(manifest.AssemblyName, context.Compilation.AssemblyName, StringComparison.Ordinal))
                {
                    if (string.IsNullOrWhiteSpace(manifest.AssemblyName))
                        Report(context, file.Path, InvalidManifest, "Target Assembly Name is required.");
                    continue;
                }
                if (!SkillTreeEnumManifestFormat.Validate(manifest, out error))
                {
                    Report(context, file.Path, InvalidManifest, error);
                    continue;
                }
                if (!trees.Add(manifest.TreeGuid))
                {
                    Report(context, file.Path, InvalidManifest, "Multiple enum manifests refer to tree " + manifest.TreeGuid + ". Keep only its generated manifest.");
                    continue;
                }
                string fullName = string.IsNullOrEmpty(manifest.Namespace) ? manifest.TypeName : manifest.Namespace + "." + manifest.TypeName;
                string firstPath;
                if (types.TryGetValue(fullName, out firstPath))
                {
                    Report(context, file.Path, DuplicateType, fullName, firstPath);
                    continue;
                }
                types.Add(fullName, file.Path);
                if (context.Compilation.GetTypeByMetadataName(fullName) != null)
                {
                    Report(context, file.Path, ExistingType, fullName);
                    continue;
                }
                context.AddSource("SkillTree_" + manifest.TreeGuid + ".g.cs", SourceText.From(Generate(manifest), Encoding.UTF8));
            }
        }

        private static string Generate(SkillTreeEnumManifest manifest)
        {
            var source = new StringBuilder("// <auto-generated />\n");
            bool hasNamespace = !string.IsNullOrEmpty(manifest.Namespace);
            if (hasNamespace) source.Append("namespace ").Append(SkillTreeEnumManifestFormat.EscapeNamespace(manifest.Namespace)).Append("\n{\n");
            source.Append("    public enum ").Append(SkillTreeEnumManifestFormat.EscapeIdentifier(manifest.TypeName)).Append(" : int\n    {\n        None = 0,\n");
            foreach (var node in manifest.Nodes.OrderBy(node => node.Id))
            {
                source.Append("        ").Append(SkillTreeEnumManifestFormat.EscapeIdentifier(SkillTreeEnumManifestFormat.ToIdentifier(node.FileName)))
                    .Append(" = ").Append(node.Id.ToString(CultureInfo.InvariantCulture)).Append(",\n");
            }
            source.Append("    }\n");
            if (hasNamespace) source.Append("}\n");
            return source.ToString();
        }

        private static void Report(GeneratorExecutionContext context, string path, DiagnosticDescriptor descriptor, params object[] arguments)
        {
            var location = Location.Create(path, new TextSpan(0, 0), new LinePositionSpan(new LinePosition(0, 0), new LinePosition(0, 0)));
            context.ReportDiagnostic(Diagnostic.Create(descriptor, location, arguments));
        }
    }
}
